router = APIRouter()


@router.post(
    "/analyze",
    response_model=TextAnalysisResponse,
    status_code=status.HTTP_200_OK,
    summary="Analyze Text Forensics",
    description=(
        "Executes multi-model transformer classification and deterministic linguistic analysis "
        "to assess whether text was generated by AI or written by a human."
    ),
)
async def analyze_text(
    request: Request,
    payload: TextAnalysisRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> TextAnalysisResponse:
    # 1. Rate limiting check per client IP
    rate_limiter.check(
        request=request,
        action="text_analysis",
        max_requests=settings.RATE_LIMIT_TEXT_MAX,
        window_seconds=settings.RATE_LIMIT_TEXT_WINDOW,
    )

    clean_text = payload.text.strip()

    # 2. Server-side validation
    if not clean_text:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Text payload cannot be empty or contain only whitespace.",
        )

    if len(clean_text) > settings.TEXT_MAX_CHARS:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Text payload exceeds maximum limit of {settings.TEXT_MAX_CHARS} characters.",
        )

    # 3. Execute forensics engine analysis
    result = text_detector.analyze_text(clean_text)
    features = result.get("features", {})

    evidence_items = [
        EvidenceItem(
            signal=item["signal"],
            metric=item.get("metric"),
            finding=item["finding"],
        )
        for item in result.get("evidence", [])
    ]

    detector_scores_data = result.get("detector_scores", {})
    ensemble_data = result.get("ensemble")

    # 4. Persist analysis record (with strict user isolation and privacy protection)
    record = TextAnalysisRecord(
        user_id=current_user.id,
        input_hash=result["input_hash"],
        text_snippet=result["text_snippet"],
        word_count=result["word_count"],
        character_count=result["character_count"],
        model_name=result["model_name"],
        model_version=result["model_version"],
        classification=result["classification"],
        confidence_score=(
            result["confidence_score"] if result["confidence_score"] is not None else 0.0
        ),
        perplexity_score=features.get("token_entropy", 0.0),
        burstiness_score=features.get("burstiness_score", 0.0),
        token_entropy=features.get("token_entropy", 0.0),
        type_token_ratio=features.get("type_token_ratio", 0.0),
        repeated_ngram_ratio=features.get("repeated_ngram_ratio", 0.0),
        evidence_json=json.dumps([item.model_dump() for item in evidence_items]),
        limitations_text=json.dumps(result.get("limitations", [])),
        ensemble_json=json.dumps(ensemble_data) if ensemble_data else None,
        status=result["status"],
        processing_time_ms=result["processing_time_ms"],
    )
    db.add(record)
    await db.flush()

    # 5. Optionally create linked case report in the platform forensic cases archive
    case_report_id: int | None = None
    if payload.save_to_cases:
        score_display = (
            f"{(result['confidence_score'] * 100):.1f}%"
            if result["confidence_score"] is not None
            else "N/A"
        )
        summary_text = (
            f"Classification: {result['classification']} (Confidence: {score_display}). "
            f"Input Hash: {result['input_hash'][:12]}... | Sample: \"{result['text_snippet']}\". "
            f"Burstiness: {features.get('burstiness_score', 0):.2f} CV, "
            f"TTR: {features.get('type_token_ratio', 0):.2f}."
        )
        report = ForensicReport(
            user_id=current_user.id,
            title=f"Text Forensics Case ({result['word_count']} words)",
            media_type="text",
            summary=summary_text,
            is_private=True,
        )
        db.add(report)
        await db.flush()
        case_report_id = report.id

    await db.commit()
    await db.refresh(record)

    parsed_detectors: dict[str, DetectorScore] = {
        k: DetectorScore(**v) for k, v in detector_scores_data.items()
    }
    parsed_ensemble = (
        EnsembleBreakdown(**ensemble_data) if ensemble_data else None
    )

    sentence_analysis_items = [
        SentenceAnalysisItem(**s) for s in result.get("sentence_analysis", [])
    ]
    paragraph_analysis_items = [
        ParagraphAnalysisItem(**p) for p in result.get("paragraph_analysis", [])
    ]
    punctuation_metrics_obj = (
        PunctuationMetrics(**result["punctuation_metrics"])
        if result.get("punctuation_metrics")
        else None
    )

    return TextAnalysisResponse(
        analysis_id=record.id,
        user_id=record.user_id,
        input_hash=record.input_hash,
        text_snippet=record.text_snippet,
        word_count=record.word_count,
        character_count=record.character_count,
        model_name=record.model_name,
        model_version=record.model_version,
        status=record.status,
        classification=record.classification,
        confidence_score=result["confidence_score"],
        ai_probability=result.get("ai_probability"),
        human_probability=result.get("human_probability"),
        perplexity_score=record.perplexity_score,
        burstiness_score=record.burstiness_score,
        token_entropy=record.token_entropy,
        type_token_ratio=record.type_token_ratio,
        repeated_ngram_ratio=record.repeated_ngram_ratio,
        detector_scores=parsed_detectors,
        ensemble=parsed_ensemble,
        sentence_analysis=sentence_analysis_items,
        paragraph_analysis=paragraph_analysis_items,
        punctuation_metrics=punctuation_metrics_obj,
        sentence_length_distribution=result.get("sentence_length_distribution", {}),
        syntactic_repetition=result.get("syntactic_repetition", {}),
        language_warning=result.get("language_warning"),
        evidence=evidence_items,
        limitations=result.get("limitations", []),
        processing_time_ms=record.processing_time_ms,
        created_at=record.created_at,
        case_report_id=case_report_id,
    )


@router.get(
    "/analyses",
    response_model=list[TextAnalysisHistoryItem],
    summary="List Analyst Text Investigations",
    description=(
        "Returns previous text forensics analyses for the authenticated analyst "
        "with strict isolation."
    ),
)
async def list_text_analyses(
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> list[TextAnalysisHistoryItem]:
    stmt = (
        select(TextAnalysisRecord)
        .where(TextAnalysisRecord.user_id == current_user.id)
        .order_by(TextAnalysisRecord.created_at.desc())
    )
    records = (await db.execute(stmt)).scalars().all()
    return [TextAnalysisHistoryItem.model_validate(r) for r in records]


@router.get(
    "/analyses/{analysis_id}",
    response_model=TextAnalysisResponse,
    summary="Get Specific Text Analysis",
    description="Retrieves a specific forensic record with strict cross-user horizontal isolation.",
)
async def get_text_analysis(
    analysis_id: int,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> TextAnalysisResponse:
    record = await db.get(TextAnalysisRecord, analysis_id)
    if not record:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Text analysis #{analysis_id} not found.",
        )

    # Cross-user authorization check
    if record.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access denied: You cannot view another analyst's private forensic analysis.",
        )

    try:
        raw_evidence = json.loads(record.evidence_json)
        evidence_items = [EvidenceItem(**item) for item in raw_evidence]
    except Exception:
        evidence_items = []

    try:
        limitations = json.loads(record.limitations_text)
    except Exception:
        limitations = []

    parsed_ensemble = None
    parsed_detectors: dict[str, DetectorScore] = {}
    sentence_items: list[SentenceAnalysisItem] = []
    paragraph_items: list[ParagraphAnalysisItem] = []
    punct_metrics: PunctuationMetrics | None = None
    sent_dist: dict[str, float] = {}
    syn_rep: dict[str, Any] = {}
    lang_warn: str | None = None

    if record.ensemble_json:
        try:
            ensemble_dict = json.loads(record.ensemble_json)
            parsed_ensemble = EnsembleBreakdown(**ensemble_dict)
            parsed_detectors = parsed_ensemble.detectors
            sentence_items = [
                SentenceAnalysisItem(**s)
                for s in ensemble_dict.get("sentence_analysis", [])
            ]
            paragraph_items = [
                ParagraphAnalysisItem(**p)
                for p in ensemble_dict.get("paragraph_analysis", [])
            ]
            if ensemble_dict.get("punctuation_metrics"):
                punct_metrics = PunctuationMetrics(**ensemble_dict["punctuation_metrics"])
            sent_dist = ensemble_dict.get("sentence_length_distribution", {})
            syn_rep = ensemble_dict.get("syntactic_repetition", {})
            lang_warn = ensemble_dict.get("language_warning")
        except Exception:
            pass

    return TextAnalysisResponse(
        analysis_id=record.id,
        user_id=record.user_id,
        input_hash=record.input_hash,
        text_snippet=record.text_snippet,
        word_count=record.word_count,
        character_count=record.character_count,
        model_name=record.model_name,
        model_version=record.model_version,
        status=record.status,
        classification=record.classification,
        confidence_score=record.confidence_score if record.confidence_score > 0 else None,
        ai_probability=record.confidence_score if "AI" in record.classification else (1.0 - record.confidence_score if "HUMAN" in record.classification else None),
        human_probability=(1.0 - record.confidence_score) if "AI" in record.classification else (record.confidence_score if "HUMAN" in record.classification else None),
        perplexity_score=record.perplexity_score,
        burstiness_score=record.burstiness_score,
        token_entropy=record.token_entropy,
        type_token_ratio=record.type_token_ratio,
        repeated_ngram_ratio=record.repeated_ngram_ratio,
        detector_scores=parsed_detectors,
        ensemble=parsed_ensemble,
        sentence_analysis=sentence_items,
        paragraph_analysis=paragraph_items,
        punctuation_metrics=punct_metrics,
        sentence_length_distribution=sent_dist,
        syntactic_repetition=syn_rep,
        language_warning=lang_warn,
        evidence=evidence_items,
        limitations=limitations,
        processing_time_ms=record.processing_time_ms,
        created_at=record.created_at,
    )


@router.get(
    "/analyses/{analysis_id}/pdf",
    summary="Download Text Analysis PDF Report",
    description="Streams an explainable forensic PDF report for a recorded text analysis.",
    response_class=Response,
    responses={
        200: {
            "content": {"application/pdf": {}},
            "description": "Returns raw PDF document bytes.",
        }
    },
)
async def download_text_analysis_pdf(
    analysis_id: int,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> Response:
    record = await db.get(TextAnalysisRecord, analysis_id)
    if not record:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Text analysis #{analysis_id} not found.",
        )

    if record.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access denied: You cannot export another analyst's private forensic analysis.",
        )

    pdf_bytes = generate_text_analysis_pdf(
        record=record,
        analyst_name=current_user.full_name or current_user.username,
    )

    filename = f"AICF-Text-Report-{record.id:05d}.pdf"
    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            "Cache-Control": "no-cache, no-store, must-revalidate",
        },
    )
